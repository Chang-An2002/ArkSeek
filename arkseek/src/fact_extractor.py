# -*- coding: utf-8 -*-
"""
L1 核心记忆的规则化事实抽取 —— 阶段二 2.1（不接LLM）

背景：方案文档4.3节里，L1的写入方式是"每轮结束后用一次LLM调用做'事实抽取'，
判断增/改/删"（Mem0的思路）。2.1明确选择不接LLM，所以这里只能退而求其次：
用一组正则规则，专门识别几种"自我介绍"类的固定句式，抽出"这个人的某个稳定
事实"存进 user_profile 表。跟阶段一的正则版查询拆解（query_decompose.py，
后来被证明依据的假设不成立、已删除）是同一种工程判断——
规则版本能覆盖已知的几种典型说法，但不理解语义，碰到规则没覆盖到的表达方式
就会漏抽，这个局限性在这里如实说明，而不是假装它是通用的语义理解。

【规则设计原则】
只挑"信息量大、句式相对固定、误判代价低"的几类自我介绍语句，每条规则绑定一个
明确的 profile key，宁可漏抽（recall低）也不乱抽（precision要高）——L1画像
是要在后续对话里被直接引用的，一条抽错的事实比不抽更糟（错误会一直沉淀下去，
影响后面每一轮对话，等于把噪音"记住"了）。

覆盖的4类事实（对应表格里的 key）：
    称呼       "我叫XX" / "叫我XX"
    身份       "我是XX研究生/学生/博士生" 这类"专业+身份"的说法
    研究方向   "我的研究方向是XX" / "我在做XX方向的研究" / "我在研究XX"
    偏好       "我喜欢XX"

【已知局限（都是实测出来的，不是猜测——见 __main__ 自测里的真实例子）】
1. 只认这几种固定句式，换一种说法就抽不到——比如"研究方向是XX"没有"我的"
   前缀、或者用"专攻XX""一直很喜欢XX"这种没覆盖的表达，都会漏判（实测：
   "我一直很喜欢做实验"抽不出"偏好"，因为规则要求"我喜欢"四个字紧挨着）。
2. 否定句大多数时候是"漏判"而不是"误判"——因为规则要求"我喜欢"/"我是"这类
   触发词跟后面内容紧挨着，"我不喜欢加班"里"我"和"喜欢"中间插了个"不"字，
   实测确实不会被误抽成"偏好=加班"，但代价是"这个人不喜欢什么"这类负面
   偏好从规则上就完全抽不出来，是被漏掉而不是被记错——两种失败模式性质不同，
   这里如实分开说明，不能笼统地说"否定句处理不好"。
3. 规则只认"方向"这两个字出现的位置，不理解语义，实测会有真正的误抽：
   "我在做兼职家教方向的努力"会被"我在做XX方向"这条规则误判成
   研究方向="兼职家教"——规则只关心句式是否匹配，不知道"家教"跟"科研"
   完全是两回事。这是规则版本必然要接受的精度代价。
4. 同一个 key 后写的事实会直接覆盖旧值（见 memory_store.py 的 upsert 逻辑），
   不会去判断"这是对旧信息的补充"还是"完全无关的新事实"——比如先说"研究方向是
   单细胞"、后面泛泛提一句"我在研究数据"，后者会把前者覆盖掉，这也是没有语义
   理解、只做字符串匹配的规则版本必然要接受的代价。
5. 不做实体消歧/归一化——"生信"和"生物信息学"会被当成两条不同的值，不会自动
   识别成同一件事。

真正解决这些问题需要接一个语言模型去理解语义、做真正的信息抽取和实体对齐，
这正是2.2（接LLM）要验证的对比对象。

【踩坑（接入conversation_memory.py联调时真实测出来的，不是设计时就想到的）】
"我的研究方向是什么？"——这是一句在问"L1画像里存的研究方向是什么"的问题，
结果被本模块的"研究方向"规则（要求"我(的)?研究方向(是|为)"后面跟着内容）
当成了一句陈述句："是"后面的"什么"两个字直接被当成了捕获值，写成了
研究方向="什么"，把之前正确存的"单细胞谱系追踪"覆盖掉了——正则规则完全
不理解"是什么"在中文里通常是疑问句，只会机械匹配"是"后面跟着的字符串。
这个bug是接入 conversation_memory.py 联调、真实问一轮"我的研究方向是
什么？"才暴露的，规则本身单独测试时不会触发（因为之前的自测用例都没有
覆盖"用问句复述陈述句触发词"这种情况）。
修复：在真正跑抽取规则之前，先判断这句话像不像一个疑问句（以"？"/"?"结尾，
或者包含"吗"），像的话直接跳过抽取，返回空列表——自我介绍几乎不会用疑问句
来表达，这是一个简单但有效的启发式判断。这也再次印证了局限2/3的教训：
规则不理解语义，只要句式上"看起来像"，就会被当成对应的意思。
"""

import re
from typing import List, Tuple


def looks_like_question(text: str) -> bool:
    """疑问句判断：不追求语言学上的严谨，只是一个廉价但有效的启发式——
    自我介绍几乎不会用疑问句表达，先挡掉这一类句子，能避免"我的研究方向是
    什么？"这种问句被误判成陈述句（见上方"踩坑"说明）。"""
    text = text.strip()
    return text.endswith(("？", "?")) or "吗" in text


# 每条规则：(正则, key, 分组下标)。用 finditer 而不是 match，允许一句话里
# 命中多条规则（比如"我叫长安，我的研究方向是单细胞谱系追踪"一句话两条事实）。
_RULES = [
    (re.compile(r"我叫([^，。,！？\s]{1,10})"), "称呼", 1),
    (re.compile(r"叫我([^，。,！？\s]{1,10})"), "称呼", 1),
    (re.compile(r"我(?:的)?研究方向(?:是|为)([^，。,！？]{1,30})"), "研究方向", 1),
    (re.compile(r"我在(?:做|研究)([^，。,！？]{1,30}?)方向(?:的研究)?"), "研究方向", 1),
    (re.compile(r"我(?:是|在读)([^，。,！？]{1,20}(?:研究生|博士生|硕士生|本科生))"), "身份", 1),
    (re.compile(r"我喜欢([^，。,！？]{1,20})"), "偏好", 1),
]


def extract_facts(text: str) -> List[Tuple[str, str]]:
    """
    从一句话里抽取 (key, value) 事实列表。命中多条规则就都返回，调用方
    （conversation_memory.py）负责逐条写入 user_profile，同一个key的处理
    顺序由调用方决定（当前实现是按抽取顺序依次覆盖写入）。
    没有命中任何规则就返回空列表——大多数句子（尤其是提问句）都不会有事实
    可抽，这是预期行为，不是bug。疑问句会被 looks_like_question 直接挡掉，
    不进入规则匹配（见模块开头"踩坑"说明）。
    """
    if looks_like_question(text):
        return []

    facts = []
    for pattern, key, group_idx in _RULES:
        for m in pattern.finditer(text):
            value = m.group(group_idx).strip()
            if value:
                facts.append((key, value))
    return facts


if __name__ == "__main__":
    tests = [
        "我叫长安，我的研究方向是单细胞谱系追踪",
        "我是生命科学专业的研究生，平时做组学测序数据分析",
        "我在做肝脏纤维化方向的研究",
        "我喜欢周末去爬山",
        "变异检测常用什么工具？",  # 纯提问句，不该抽出任何事实
        "我不喜欢加班",  # 已知局限2：不会误抽，但也完全抽不到"负面偏好"这个事实
        "我一直很喜欢做实验",  # 已知局限1：触发词不紧挨着，漏判
        "我在做兼职家教方向的努力",  # 已知局限3：真正的误抽，"家教"被当成研究方向
        "我的研究方向是什么？",  # 踩坑：疑问句会被"研究方向"规则误判成陈述句，现已修复为返回[]
    ]
    for t in tests:
        print(f"{t!r}\n  -> {extract_facts(t)}")
