class SubQuery(TypedDict):
    id: str
    query: str
    depends_on: List[str]


class DecomposePlan(TypedDict):
    sub_queries: List[SubQuery]


class SubAnswer:
    """单个子查询的执行结果——`conversation_memory.py`里`_try_answer_from_
    history()`/`_try_answer_from_local_kb()`/`_try_answer_from_wiki_page()`
    现在统一返回这个，取代原来的裸字符串。放在这个文件而不是
    conversation_memory.py，是因为`synthesize()`也要读它的字段，避免两个
    文件互相导入对方的类型定义。

    display：完整的、可以直接原样展示给用户的最终格式化文本（含【...】头和
    引用来源脚注，或者gate没过时的拒答文案）——单轮对话场景下，调用方只用
    这个字段，语义跟改动前的裸字符串返回值完全一致。

    core：干净的核心自然语言答案，去掉了头尾格式包装，只在多跳编排器把这
    一步的结果当作背景喂给依赖它的下一个子查询时使用。ok=False，或者gate
    通过但LLM生成不可用/失败退回"展示证据列表"格式时，core给空字符串——
    一个"没查到"或者"没能生成成一句话"的结果不该被当作确定的前提喂给依赖
    它的下一步，编排器看到core为空会自己决定要不要退而求其次用display。

    ok：True=真的有可信证据支撑（gate通过，不管有没有生成成自然语言）；
    False=没查到/gate没过——display仍然是一个诚实、可以直接展示的兜底
    文案，只是不能被多跳编排器当作"这一跳查到了确定答案"看待。

    candidates：F（多候选页面消歧）新增字段，默认空列表，绝大多数调用方
    完全不用管这个字段。只有`_try_answer_from_wiki_page()`在`detect_
    candidates=True`时才会填（见该方法说明），长度<=1表示"没检测出歧义"
    （跟不填/空列表语义一致，`_answer_multi_hop()`按"没有歧义"处理）；
    长度>1才代表这一跳的资料原文里确实存在不止一个候选，触发fan-out。
    """

    def __init__(self, display: str, core: str = "", ok: bool = True, candidates: Optional[List[str]] = None,
                 source: str = "", refs: Optional[List[str]] = None):
        self.display = display
        self.core = core
        self.ok = ok
        self.candidates = candidates or []
        # 这部分答案来自哪里："web"（联网搜索）/"llm"（大模型自身知识）这两种
        # 是未经知识库核实的来源，多跳合并时要分段单独标注；其它（wiki/本地
        # 知识库/历史/画像，或者没填）按原来的方式合并。见conversation_memory.py
        # "QQ群压力测试准备（二）"一节。
        self.source = source
        # 这部分答案具体来自哪些资料（"prts.wiki/能天使"、"作者2025年7月5日 JC讲稿：…"），
        # 复合问题里知识来源那一段要单独标注来源时用（用户的要求：不然网络搜索那段
        # 末尾的"以上内容来自网络搜索"会让人以为整个回答都是搜来的）
        self.refs = refs or []

    def __repr__(self):
        return f"SubAnswer(ok={self.ok}, core={self.core!r}, display={self.display[:30]!r}...)"


def _single_query_plan(text: str) -> DecomposePlan:
    """退化路径：不拆分，原句作为唯一子查询——语义上等价于"这次编排完全
    没有发生"，见模块开头"这次改动的代价"一节。所有调用decompose()的地方
    看到这种形状的返回值，都应该直接走原来的单查询路径，不进入多跳编排。
    """
    return {"sub_queries": [{"id": "q1", "query": text, "depends_on": []}]}


_DECOMPOSE_SYSTEM_PROMPT = """\
只处理当前这句话的任务，不能把旧背景中的请求重新加入计划。当前仅在陈述个人偏好、
设置今后的回答格式，且上一轮未向用户索取这些信息时，不创建攻略/推荐/资料查询子问，
保留为一个原句查询交给路由确认。若当前明确提出查询或继续任务，或者正在回答上一轮
为原请求提出的澄清问题，则按实际请求规划，不能把这些输入一概当成只需确认。
你是一个记忆系统里负责"问题拆解"的组件，工作在真正的路由判断（该查明日
方舟wiki、该查本地知识库、该翻旧账、还是纯聊天这四选一）之前——你不负责
回答问题，也不负责判断该去哪查，只负责判断这一句话要不要拆成多个先后
执行的"信息需求"才能完整回答。

绝大多数问题只有一个信息需求，不需要拆分——拿不准的时候，优先不拆，按
原句输出一个子查询。只有明确符合下面两种情况之一时才需要拆：

1.【独立并列】这句话里包含两个或以上互不依赖的信息需求，各自可能需要查
   不同的知识来源（比如一部分该翻旧账、一部分该查明日方舟wiki；或者一句
   话里问了好几个不同干员各自的信息）——彼此谁先查谁后查都无所谓，也不
   需要用到对方的结果。
   注意①：同一个实体（同一个干员/同一个知识来源页面）下的多个属性——即使
   用"另外""还有"这种听起来并列的语气词连接（比如"能天使的技能是什么，
   另外模组呢"）——不算独立并列，因为这些信息一次检索同一个来源就能全部
   覆盖，不需要分开查、也没有不同的知识来源，应该按不拆分处理。
   注意②：判断"是不是两个不同实体各自的信息"，不能只看句子里有没有"分别"
   这种明确的并列标记词——"铃兰和忍冬的基建技能是什么"跟"铃兰、忍冬的基建
   技能分别是什么"是同一种情况，都该拆成两个独立子查询，不要因为没写"分别"
   就误判成能用一次检索解决（现有检索一次只能精确匹配一个实体对应的单个
   wiki页面，没法用"铃兰 忍冬"这种把两个实体名拼在一起的关键词一次查到）。
   问的是两个实体之间的关系/有没有联动这类问题时同样适用：要回答"A和B是否
   存在联动"，也得先分别查到A、B各自的信息，这一步不该替后面的"综合判断"
   把关系结论抢答出来，仍然按拆成两个独立子查询处理，让后面合并步骤根据
   两份资料自己判断有没有关系。

2.【链式依赖】后一个信息需求必须先知道前一个信息需求的答案，才问得出来
   （比如"A的B的C是什么"这种，要先查出"A的B是谁/是什么"，才能接着问"这个
   人/这个东西的C是什么"）。中间实体"B"既可以是单独一个人/一件事，也可以
   是一份名单/一组人（比如"A的同事"），后一步在名单里的每一项上分别追问
   属性，同样算链式依赖，不因为B是复数就不用拆。
   注意①：判断要不要拆成链式依赖，只看"这句话在语言结构上有没有一个中间
   实体需要先确认下来"，不能因为你自己训练数据里可能"记得"这个中间实体
   是谁，就跳过拆分、当成一步到位的单一问题处理。哪怕你很有把握"B"具体
   指的是谁，也应该老老实实拆成两步——执行阶段需要真的发起检索去确认，
   不能靠你的训练数据记忆替执行阶段把这一步跳过，那样等于没有真的查证，
   只是蒙对了而已（这跟真机测试里"玛恩纳的侄女"必须真的分两步查证、不能
   靠训练数据记忆蒙对是同一个原则，只是这次错误发生在拆解这一步，不是
   执行这一步）。
   注意②：判断要不要拆，看的是问题背后"要不要先确认一个中间实体"这个
   结构本身，不要被表面的措辞带偏——"A的B包含哪些C""A的B都有什么C"这种
   问整体集合的问法，跟"A的B的C分别是什么"这种带"分别"字样的问法，只要
   问的是同一件事，就该拆出同一份plan，不能因为一种问法里没出现"分别"、
   或者读起来像是在问一个笼统的整体属性，就误判成能一步到位查到的单一
   问题（同一件事换个自然说法，不应该得到不一样的拆解结果）。
   注意③："这个课题""这个project""这项研究""{OWNER}的课题""作者的课题""你们的实验"这类
   说法，在这个机器人里固定指{OWNER}（开发这个机器人的人）自己的科研课题（本地知识库里的课题报告），
   是问题的主语，不是需要先查清楚的中间实体——"这个课题是和哪个课题组合作
   的""这个课题用了什么小鼠"都是一步就能查的单一问题，不要拆出"这个课题是
   哪个课题"这种子查询（知识库扩充的真机验证里出现过：拆出来的这一步被拿去
   联网搜索，搜回一堆不相干的"课题"）。

给每个子查询一个id（q1/q2/q3...，按应该执行的先后顺序）；query给一句完整、
自然的中文问句——链式依赖的后续子查询，可以像人正常追问那样用代词/省略
指代前一步的答案（比如"她的职业是什么"），不需要把前一步的答案硬套进这句
话里写出来，执行的时候会把前一步已经查到的结果当作背景一并交给下一步，
你不需要自己替换。depends_on给出这个子查询依赖哪些更早出现的子查询id
（互不依赖的给空列表，depends_on里的id必须是排在它自己前面的某个id）。

最多拆成4个子查询；如果一句话看起来需要拆出比这更多的部分，只挑最核心的
几个信息需求来拆，或者干脆按不拆处理。

按格式输出JSON，不要输出JSON之外的任何文字：
{"sub_queries": [{"id": "q1", "query": "...", "depends_on": []}, ...]}

有时你会在这句话之前额外看到一段"最近对话"——那是这句话之前发生的背景，
只用来帮你理解这句话本身，不要把"最近对话"里的内容当成需要拆分的对象。
即使"最近对话"里最后一轮是一个上一次没有查到答案、看起来还没解决的问题，
也不能因为它"还没解决"就顺手把它当成这次也要查的一个子查询——除非这句话
本身的用词（代词/省略）明确表示在追问同一件事，否则只按这句话字面问的
内容来拆，不要额外凭"最近对话"生成任何这句话没有问过的子查询。

几个例子：

输入："能天使是什么职业？"
输出：{"sub_queries": [{"id": "q1", "query": "能天使是什么职业？", "depends_on": []}]}
（单一信息需求，不需要拆分，query原样保留）

输入："变异检测常用什么工具？"
输出：{"sub_queries": [{"id": "q1", "query": "变异检测常用什么工具？", "depends_on": []}]}

输入："能天使的三技能名称是什么，另外模组呢？"
输出：{"sub_queries": [{"id": "q1", "query": "能天使的三技能名称是什么，另外模组呢？", "depends_on": []}]}
（虽然有"另外"这个听起来像并列的语气词，但"技能名称"和"模组"都是同一个
干员——能天使——的属性，同一个wiki页面一次检索就能同时覆盖，不属于"需要
查不同知识来源"，也不是链式依赖，不要拆分，query原样保留）

输入："我们组之前决定用什么做向量数据库来着，另外能天使是什么种族？"
输出：{"sub_queries": [
  {"id": "q1", "query": "我们组之前决定用什么做向量数据库来着", "depends_on": []},
  {"id": "q2", "query": "能天使是什么种族？", "depends_on": []}
]}
（两部分互不依赖，一个该翻旧账、一个该查明日方舟wiki，拆成两个独立子查询，
谁先执行都可以）

输入："能天使、德克萨斯的天赋分别是什么？"
输出：{"sub_queries": [
  {"id": "q1", "query": "能天使的天赋是什么？", "depends_on": []},
  {"id": "q2", "query": "德克萨斯的天赋是什么？", "depends_on": []}
]}
（两个干员各自独立，互不依赖）

输入："铃兰和忍冬的基建技能是什么？"
输出：{"sub_queries": [
  {"id": "q1", "query": "铃兰的基建技能是什么？", "depends_on": []},
  {"id": "q2", "query": "忍冬的基建技能是什么？", "depends_on": []}
]}
（虽然没有"分别"这种字面标记，但铃兰、忍冬是两个不同干员，各自的基建技能
是两个独立的信息需求，同样要拆分）

输入："铃兰和忍冬的基建技能是否存在联动？"
输出：{"sub_queries": [
  {"id": "q1", "query": "铃兰的基建技能是什么？", "depends_on": []},
  {"id": "q2", "query": "忍冬的基建技能是什么？", "depends_on": []}
]}
（问的虽然是"是否存在联动"这种关系型问题，但要回答它仍然得先分别查到两个
干员各自的基建技能，这一步不用越俎代庖去判断有没有联动，仍然拆成两个独立
子查询，联动结论交给后面合并的步骤根据两份资料自己判断）

输入（最近对话：
user：它现在进展到哪一步了？
assistant：检索到的内容里没有提到具体进展到哪一步，答不上来。
）
当前这句话：能天使是什么职业？
输出：{"sub_queries": [{"id": "q1", "query": "能天使是什么职业？", "depends_on": []}]}
（"最近对话"里上一轮问的"进展到哪一步了"这次没有查到答案，但当前这句话
是全新的、跟上一轮无关的问题，不能因为上一轮"还没解决"就顺手把它也塞进
这次的拆解结果里当成一个额外子查询——只处理这句话字面问的内容，原样
保留、不拆分）

输入："玛恩纳的侄女的职业是什么？"
输出：{"sub_queries": [
  {"id": "q1", "query": "玛恩纳的侄女是谁？", "depends_on": []},
  {"id": "q2", "query": "她的职业是什么？", "depends_on": ["q1"]}
]}
（第二步必须先知道"侄女是谁"才问得出"职业"，是链式依赖；第二句用代词"她"
自然追问即可，不要写成"玛恩纳的侄女的职业是什么"这种把第一步答案硬套
进去的形式）

输入："W的异格是什么职业？"
输出：{"sub_queries": [
  {"id": "q1", "query": "W的异格是谁？", "depends_on": []},
  {"id": "q2", "query": "她的职业是什么？", "depends_on": ["q1"]}
]}
（跟"玛恩纳的侄女的职业"是完全同一种结构——"异格"是需要先确认下来的
中间实体，即使你自己"知道"W的异格具体是谁，也不能因此当成一步到位的
单一问题处理，仍然要拆成两步，让执行阶段真的查证一遍）

输入："能天使的同事的种族分别是什么？"
输出：{"sub_queries": [
  {"id": "q1", "query": "能天使的同事有哪些？", "depends_on": []},
  {"id": "q2", "query": "他们的种族分别是什么？", "depends_on": ["q1"]}
]}
（链式依赖同样适用于中间实体是"一群人/一个列表"而不是单独一个人的情况——
"同事"不是一个人，是要先查出来的一份名单，第二步再对这份名单里的每个人
分别问种族，仍然是"先确认中间实体，再问它的属性"这个结构，只是中间实体
这次是复数）

输入："能天使的同事包含哪些种族？"
输出：{"sub_queries": [
  {"id": "q1", "query": "能天使的同事有哪些？", "depends_on": []},
  {"id": "q2", "query": "他们的种族分别是什么？", "depends_on": ["q1"]}
]}
（跟上一个例子是完全同一个问题，只是换了个问法——"A的B包含哪些C"和
"A的B的C分别是什么"表达的是同一件事，不要因为这次问法里没有出现"分别"
这种字面标记、或者"包含哪些"读起来像是在问一个整体属性，就误判成能一步
到位单一查询处理。判断要不要拆、拆成什么样，看的应该是问题背后的信息
依赖结构本身，不是这句话恰好用了哪几个字——同一个结构不应该因为换一种
自然的问法就得到不一样的拆解结果）

只输出JSON对象本身，不要加任何解释、不要用markdown代码块包裹。
"""
_DECOMPOSE_SYSTEM_PROMPT = fill_owner(_DECOMPOSE_SYSTEM_PROMPT)


def _validate_plan(data) -> Optional[DecomposePlan]:
    """校验`decompose()`拿到的JSON形状是不是一个合法的plan：sub_queries是
    1~MAX_SUB_QUERIES条、每条id/query/depends_on字段类型都对、id不重复、
    depends_on只能引用排在自己前面的id（这一条保证按列表顺序执行天然满足
    依赖关系，不需要真正的拓扑排序，见模块开头"为什么不做真正的DAG拓扑
    排序引擎"一节）。任何一条不满足，整体判定为解析失败，返回None——跟
    `wiki_router.py`/`llm_l1.py`一样的"不给半成品"原则。
    """
    if not isinstance(data, dict):
        return None
    sub_queries = data.get("sub_queries")
    if not isinstance(sub_queries, list) or not (1 <= len(sub_queries) <= MAX_SUB_QUERIES):
        return None

    seen_ids: set = set()
    validated: List[SubQuery] = []
    for item in sub_queries:
        if not isinstance(item, dict):
            return None
        qid = item.get("id")
        query = item.get("query")
        depends_on = item.get("depends_on", [])
        if not isinstance(qid, str) or not qid or qid in seen_ids:
            return None
        if not isinstance(query, str) or not query.strip():
            return None
        if not isinstance(depends_on, list) or not all(isinstance(d, str) for d in depends_on):
            return None
        if not set(depends_on).issubset(seen_ids):
            # 依赖了一个还没出现过（或者压根不存在）的id，不是合法的拓扑序
            return None
        seen_ids.add(qid)
        validated.append({"id": qid, "query": query.strip(), "depends_on": depends_on})

    return {"sub_queries": validated}


def decompose(text: str, client, recent_context=None) -> DecomposePlan:
    """核心入口之一。client 是 llm_client.py 里 build_llm_client() 返回的对象。

    退化路径（返回`_single_query_plan(text)`，等价于"这次编排完全没有
    发生"）覆盖三种情况：①client不可用（`is_real=False`，2.1或者LLM调用
    失败的场景，没有更低配的规则版可退，理由同`wiki_router.py`）；②LLM
    调用本身失败（`client.chat()`返回None）；③返回的内容解析/校验不通过
    （格式不对、字段缺失、依赖关系不合法）。三种情况都不报错、不抛异常，
    调用方（`conversation_memory.py`的`_dispatch_with_planner()`）看到单
    子查询的plan，直接走原来的`_dispatch_with_router()`单查询路径，跟没有
    这层编排时行为完全一致。
    """
    if not getattr(client, "is_real", False):
        return _single_query_plan(text)

    messages = [
        {"role": "system", "content": _DECOMPOSE_SYSTEM_PROMPT},
        {"role": "user", "content": with_current_message(recent_context, text)},
    ]
    raw = client.chat(messages, caller="decompose()")
    if raw is None:
        return _single_query_plan(text)

    parsed = _validate_plan(try_parse_json(strip_json_fence(raw)))
    if parsed is None:
        print(f"[query_planner] 分解失败或格式不合法（原始输出：{raw!r}），"
              f"回退到不拆分，按原句处理。")
        return _single_query_plan(text)

    # 只在真的拆出多个子查询时才打印——单子查询是"什么都没发生"的默认
    # 情况，不需要刷屏；一旦真的拆分了，把每个子查询的query/depends_on
    # 亮出来，方便真机验证时直接确认"这句话到底有没有被拆、拆成了什么
    # 样子"，不用再靠最终回答的措辞反推。2026-09第三轮真机验证时发现，
    # 光靠回答文本很难分清"决定不拆分、单查询里如实说没查到"和"拆分了但
    # 其中一个子查询没查到"这两种情况——两种在最终措辞上可能很像，但对应
    # 的是完全不同的执行路径，加这行打印直接消除歧义。
    sub_queries = parsed["sub_queries"]
    if len(sub_queries) > 1:
        parts = "; ".join(
            f"{sq['id']}='{sq['query']}'（依赖：{sq['depends_on'] or '无'}）"
            for sq in sub_queries
        )
        print(f"[query_planner] 拆成了{len(sub_queries)}个子查询：{parts}")
    return parsed


_RESOLVE_SYSTEM_PROMPT = """\
你是一个记忆系统里负责"让检索用的问题更完整"的组件。你会收到一句可能带
代词/省略指代的问题，以及它前面已经查到的一些背景信息。

如果这句话本身已经完整、不需要看背景就能看懂，原样输出这句话；如果这句话
里有代词/省略指代（"她""这个""那个人"）需要借助背景才能看懂，把它改写成
一句不用看背景也能看懂的完整问题，只替换需要补全的部分，其它保持原样，
不要额外添加背景里没有直接支持的内容，也不要把背景本身当成问题的一部分
复述进去。

省略了对象的请求也算不完整，要补上：像"简单介绍一下吧""详细说说""展开讲讲"
"它有什么用"这类话，没写介绍/说的是什么，指的就是最近一两轮正在聊的那个东西，
把它补进去。例子：
背景：……最近一次JC是9月12日，讲的是SPACE-seq这篇文章……
句子：嗯，简单介绍一下吧
改写：简单介绍一下SPACE-seq这篇文章
只换了"去哪里找"、没重复问的是什么的追问（"那原文里是怎么说的""PPT里呢""文献里有没有
提到"），问的还是上一句那个问题，要把那个问题完整带上，不能只补文献名。例子：
背景：用户：SPACE-seq里面有说为什么要用Slide-seq吗 / 助手：讲稿里只顺带提了一句兼容性……
句子：那原文里是怎么说的
改写：SPACE-seq原文里是怎么说为什么要用Slide-seq的

有背景时，要处理的是标着"当前这句话："的那一句；背景里更早的请求不管有没有
被回答，都不是这次要改写的对象。

你不是在回答这句话：不管这句话是提问还是请求（"介绍一下……""帮我总结……"），
都只输出改写后的这句话本身，保持原来的提问/请求形式和其它要求（比如字数限制），
不要回答它、不要说"抱歉/好的"、也不要补充你猜的答案内容。

"我""我的"永远指说这句话的人自己。只有背景里明确注明"当前跟你说话的就是{OWNER}本人"
时，才把它换成"{OWNER}""{OWNER}的"；没有这句注明时（比如群聊里说话的是别的群友，
即使最近对话里{OWNER}刚问过同样的问题），"我"不是{OWNER}，不要换成{OWNER}或者任何
别人的名字，保留"我"原样即可。有注明时的例子：
背景：（当前跟你说话的就是{OWNER}本人……）
句子：帮我总结下我的中期报告，别太长
改写：帮我总结下{OWNER}的中期报告，别太长

背景里如果出现"（已查到的信息）..."这种标记，它是当前这个问题所在的
查询链路里刚确认下来的直接依据，比背景里其它普通历史对话更可信、更
应该优先采用——如果"已查到的信息"和更早的普通历史看起来指向不一样的
内容或不一样的人/事，以"已查到的信息"为准，不要被更早、可能更详细的
历史内容带偏。

只输出改写后的问题本身，不要输出任何解释、不要加引号、不要用markdown。
"""


def resolve_for_retrieval(text: str, context_rows, client) -> str:
    """只在多跳编排器执行"有依赖"的子查询时才会被调用，见模块开头"L0上下文
    窗口未接入路由判断的下游缺口，这次怎么补"一节。不是全局生效的功能：
    普通单轮对话（不经过多跳编排）完全不会调用这个函数，行为不受影响。

    2026-09F真机测试第一轮暴露的更新（见模块开头"F真机测试第一轮"一节的
    Fix A）：这个函数原来只在子查询被判给route="local_kb"/"history"时才
    调用，wiki路由完全依赖`route_query()`自己解析代词/依赖信息——结果在
    "能天使的同事"这个fan-out场景里，`route_query()`在fan-out注入的候选
    信息和更早的L0多轮历史之间选错了，把关键词解析成了"能天使"而不是具体
    某个候选人。修复后只要这个子查询有`depends_on`，不管之后会被路由到
    哪个分支（wiki/local_kb/history都一样），调用方都会先统一调用一次这个
    函数把代词/省略补全，再拿补全后的文本去路由——所以现在这个函数是在
    "路由判断之前"跑的，而不是"路由判断之后只给local_kb/history补一刀"。

    2026-09F真机测试第二轮的追加更新：Fix A解决了"这个函数会不会被调用"
    的问题，但没解决"调用了也不一定改写对"——同一个"能天使的同事"场景里，
    fan-out每个分支新注入的候选名字和这次对话更早的多轮历史（如果之前
    问过同义问法，历史里可能已经完整提到过所有候选）会一起出现在context
    里，没有优先级之分时，LLM有时候会被更详细的历史带偏，解析出跟这个
    分支不对应的名字。两处应对：①`_RESOLVE_SYSTEM_PROMPT`补了"`已查到的
    信息`标记优先于普通历史"的说明，作为通用防线；②对于`conversation_
    memory.py`里fan-out每个分支自己的下游子查询执行，这个分支该问的是谁
    在代码层面已经确定（不需要LLM去猜），干脆不传`recent_context`，直接
    去掉噪声源，比只靠一条prompt指令更可靠——完整说明见`conversation_
    memory.py`的`_answer_multi_hop_with_fanout()`模块内新增的docstring
    小节。

    context_rows为空、或者client不可用时直接原样返回text，不引入额外开销
    也不引入新的失败模式；LLM调用失败/返回空同样原样返回text——宁可退回
    "检索质量可能因为代词没解析掉而打折扣"这个已知局限，也不要让一次改写
    失败拖累整个子查询。
    """
    if not context_rows or not getattr(client, "is_real", False):
        return text

    messages = [
        {"role": "system", "content": fill_owner(_RESOLVE_SYSTEM_PROMPT)},
        {"role": "user", "content": with_current_message(context_rows, text)},
    ]
    raw = client.chat(messages, caller="resolve_for_retrieval()")
    if raw is None or not raw.strip():
        return text
    rewritten = raw.strip()
    reason = _rewrite_rejection_reason(text, rewritten)
    owner_speaking = any(_OWNER_SPEAKING_MARK in str(_row_text(r)) for r in context_rows)
    if not reason and not owner_speaking and "我" in text and "我" not in rewritten \
            and OWNER_NAME in rewritten and OWNER_NAME not in text:
        # 群里别人问"我的开题报告"，最近对话里长安刚问过同样的问题，改写把提问者的
        # "我"换成了长安（2026-09-29真机，3/3）。说话的不是长安时，"我"不能变成长安
        reason = f"说话的不是{OWNER_NAME}，却把提问者的\"我\"换成了{OWNER_NAME}"
    if reason:
        print(f"[query_planner] 改写结果不像原来的问题（{reason}），丢掉，用原句检索："
              f"{text!r}（改写结果：{rewritten[:60]!r}）")
        return text
    return rewritten


# 【第二道防线：改写结果要"还是原来那个问题"（2026-09-29）】
# 真机里主人问"那你介绍一下我的开题报告吧，100字以内"，改写本该只把"我的"换成
# "长安的"，6次里3次出错：编出不存在的开题报告题目、或者直接写成一段回答（"抱歉，
# 我这里没有你的开题报告内容……"）。拿去检索必然查不到，一路退到联网/大模型自身知识。
# 第一道防线是prompt（写明"只改写不回答"）；这里是代码校验，成熟做法里改写/查询扩展
# 这类辅助步骤的输出都要校验、不合格就退回原句。合格的改写只是把代词/省略补成具体
# 名字，原句里的实词基本都还在；所以看原句的实词有多少出现在改写结果里，太少就丢掉。
# 代词、语气词、标点不算实词（它们本来就可能被替换掉）；原句没有实词（"那她呢"）时
# 不做这项检查。
_OWNER_SPEAKING_MARK = f"当前跟你说话的就是{OWNER_NAME}本人"  # conversation_memory._build_planner_context()的主人说明


def _row_text(row) -> str:
    try:
        return row["text"]
    except (KeyError, IndexError, TypeError):
        return ""


_REWRITE_FUNCTION_CHARS = set("我你他她它们这那个些的了吗吧呢啊呀嘛么哦呗就还也都")
_REWRITE_MIN_KEPT = 0.6
_ANSWER_LIKE_PREFIXES = ("抱歉", "不好意思", "对不起", "好的", "当然", "没问题", "我这里", "我这边")


def _content_units(text: str) -> List[str]:
    """实词单位：连续的字母/数字算一个（"100""CRISPR"），汉字一个字算一个。"""
    units = []
    for m in re.finditer(r"[A-Za-z0-9]+|[一-鿿]", text):
        u = m.group(0)
        if len(u) == 1 and u in _REWRITE_FUNCTION_CHARS:
            continue
        units.append(u.lower())
    return units


def _rewrite_rejection_reason(original: str, rewritten: str) -> str:
    """改写结果合格返回空字符串，不合格返回原因（写进日志）。"""
    if rewritten.startswith(_ANSWER_LIKE_PREFIXES) and not original.startswith(_ANSWER_LIKE_PREFIXES):
        return "像是在回答而不是在提问"
    units = _content_units(original)
    if not units:
        return ""
    low = rewritten.lower()
    kept = sum(1 for u in units if u in low) / len(units)
    if kept < _REWRITE_MIN_KEPT:
        return f"原句的实词只保留了{kept:.0%}"
    return ""


_SYNTHESIZE_SYSTEM_PROMPT = """\
你是一个记忆系统里负责"把多个已经查到的子答案合并成一句完整回答"的组件。
用户问了一个需要拆成几个部分才能查清楚的问题，每个部分现在都已经有了
明确的（或者确认查不到的）结果，你的任务是把这些结果合并成一段连贯、
自然的回答（跟用户提问的语言一致），直接回应用户最初问的那个完整问题——不要逐条罗列"第一
部分...第二部分..."这种报告式的格式，要像正常回答一样组织成连贯的话。

只根据下面给出的各部分结果作答，不要额外编造或引申没有出现过的内容；如果
某个部分明确没查到，在回答里如实带一句提及，不要假装每部分都有确定答案。

这一条尤其重要：如果某个部分的结果是"没有查到可信的答案"，即使你自己
"记得"或者很有把握这个问题的真实答案是什么（比如这是一个你训练数据里
见过的公开信息、知名角色的设定），也必须老实说这部分没查到，不能用你
自己的背景知识替代检索结果去补全——检索到什么、查没查到，只能以下面
给出的各部分结果为准，你自己"知道"答案这件事不能作为回答的依据，这跟
"这一跳到底有没有真的检索验证过"是同一个原则，只是这次发生在合并这一步，
不是检索或拆解那一步。

一个例子：

输入：
用户最初问的问题：苇草的异格是什么职业？

拆解后各部分的结果：

[q1] 问题：苇草的异格是谁？
结果：焰影苇草

[q2] 问题：她的职业是什么？
结果：没有查到可信的答案

正确输出："苇草的异格是焰影苇草，不过没有查到她的职业信息。"
错误输出（不要这样做）："苇草的异格是焰影苇草，职业是医疗干员，具体
分支是咒愈师……"——即使你自己知道这大概率是对的，只要上面的结果里
写的是"没有查到可信的答案"，就不能在回答里编出具体的职业、分支这些
细节，哪怕只写一半、只提一个大概方向也不行。

只输出回答正文本身，不要输出"根据以上信息"之类的开场白，不要用markdown
标题。
"""


def synthesize(original_text: str, plan: DecomposePlan,
                sub_results: Dict[str, SubAnswer], client) -> Optional[str]:
    """把多跳编排器执行完的各个子查询结果合并成一句面向用户的最终回答。

    sub_results：{子查询id: SubAnswer}。只包含编排器实际执行到的部分——
    链式依赖的前置子查询失败时，编排器会提前终止整个流程、不会走到这一步；
    独立并列的某个子查询失败，编排器会把失败结果也如实记进sub_results
    （ok=False），让这里能诚实地说"这部分没查到"，完整逻辑见
    `conversation_memory.py`的`_answer_multi_hop()`。

    返回None表示这轮没能合并（LLM不可用/调用失败），调用方应该退回一个
    更朴素的拼接格式，不隐藏"生成失败"这件事本身——跟`llm_generate.py`
    "生成失败退回展示证据"是同一套降级哲学。

    【2026-09真机测试暴露的真实bug：合并这一步会绕过检索验证、直接拿
    训练数据记忆填空】用户测"W的异格是什么职业"/"陈的异格是什么职业"时，
    对应候选（维什戴尔/假日威龙陈/赤刃明霄陈）的`llm_generate_answer()`
    因为MiniMax内容安全分类器拒绝而失败，一路退到`_try_answer_from_
    local_kb()`（用户自己的生信论文知识库，跟明日方舟毫不相关）、置信度
    gate没通过，最终这个子查询在`sub_results`里如实记成了ok=False、
    "没有查到可信的答案"。按设计，`synthesize()`看到这种记录应该在最终
    回答里如实说"这部分没查到"——但真机测试里最终回答反而给出了一段
    非常具体、看起来言之凿凿的职业描述（"投掷手""散射手""术战者"这类
    细节），跟"没查到"记录完全对不上。根因：`synthesize()`只是把
    sub_results里的记录喂给LLM去组织成一段话，没有任何机制阻止LLM在
    看到"没有查到可信的答案"时，用自己训练数据里记得的这个知名角色的
    公开设定去替补这个空缺——这些角色信息确实是公开、大概率也是对的，
    但"答案凑巧对"不等于"这一跳真的被检索验证过"，这跟本模块开头
    decompose()那次"不能靠训练数据记忆跳过拆分"是完全同一类问题，只是
    这次发生在最后合并这一步，比之前更隐蔽——因为最终呈现给用户的是一句
    读起来很确定、格式和其它老实检索到的部分一模一样的话，用户根本看不出
    这部分其实没有真的经过检索验证，换一个冷门角色/冷门属性大概率就会
    编错。修复：给`_SYNTHESIZE_SYSTEM_PROMPT`加了一条明确指令，要求即使
    LLM自己"记得"或者很有把握某个没查到的部分的真实答案，也必须老实说
    没查到，不能拿自己的背景知识替代检索结果。

    【追加更新：第一版修复（只有抽象指令）真机验证没压住，加了具体反例
    才压住】用户很快用"苇草的异格是什么职业"重新触发了同样的失败场景
    （焰影苇草那次`llm_generate_answer()`同样被内容安全分类器拒绝），
    结果`synthesize()`依然给出了一段详细到离谱的职业描述（连本体苇草的
    职业都编出来对比了，这个信息在任何一个sub_result里都不存在，纯属
    凭空生造），说明只给一条抽象指令（"不能拿背景知识替代检索结果"）
    压不住这个倾向——这其实跟`llm_l1.py`那两次真实修复（HANDOFF.md里的
    ③④）的经验完全一致：那两次也都是"先加抽象规则不够、必须配一条具体
    反例才真的压住"，只讲道理不给例子，LLM该犯的错该越权的地方一样会越权，
    这次一开始只顾着加抽象指令、没有照搬这条已经验证过的经验，是这次
    修复没有一次做到位的直接原因。第二版加了一个完整的"正确输出 vs 错误
    输出"对比例子，用的正是"苇草的异格"这次真实撞到的场景本身——这处
    加固同样需要用户重新触发一次真实的生成失败场景才能验证，沙盒假LLM
    测不出LLM会不会真的压住用训练记忆填空的冲动。

    【追加更新：加了一行调试打印，让"这部分到底有没有查到"能被用户肉眼
    直接核对】用户拿"苇草的异格是什么职业"这次真实log反问："wiki明明
    精确命中了《焰影苇草》这个页面，为什么你还说这是编造的？"——这是个
    很合理的疑问，值得把"页面命中"和"生成成功"这两件事的区别摆到台面上
    让用户自己核实，而不是只凭我这边的代码推理下结论：日志里"命中精确
    页面标题"只代表`route_query()`那次LLM调用选对了该查哪个页面，紧接着
    还有一次单独的`llm_generate_answer()`调用要去读那个页面的正文、把它
    组织成一句话——这次真机log里恰恰是这一步被内容安全分类器拒了。按
    `_try_answer_from_wiki_page()`的代码（本函数往上一段），生成失败时
    整条wiki结果被完全丢弃、返回None（不像`_try_answer_from_local_kb()`
    那样还有"展示原始证据"的兜底），调用方会转去试本地知识库——但本地
    知识库是用户自己的生信论文，跟明日方舟毫无关系，置信度gate几乎必然
    拒绝，最终这个子查询在`sub_results`里如实记成`ok=False`。也就是说
    职业这部分从始至终没有任何一次成功的检索/生成，最终答案里那些具体
    职业描述不可能是从这次对话里"抄"来的。为了不只靠这段推理说服用户、
    让他们能在自己的终端里亲眼核对，加了这行打印：把交给LLM合并的
    `parts_text`原样打印出来，下次同样的失败场景再出现时，用户能直接
    在日志里看到某一条写的就是"没有查到可信的答案"，再对照最终回答是不是
    凭空多出了这条里完全没有的具体内容。
    """
    if not getattr(client, "is_real", False):
        return None

    parts = []
    for sq in plan["sub_queries"]:
        answer = sub_results.get(sq["id"])
        if answer is None or not answer.ok:
            parts.append(f"[{sq['id']}] 问题：{sq['query']}\n结果：没有查到可信的答案")
        else:
            core_text = answer.core if answer.core else answer.display
            parts.append(f"[{sq['id']}] 问题：{sq['query']}\n结果：{core_text}")
    parts_text = "\n\n".join(parts)

    print(f"[query_planner] synthesize() 提交给大模型合并的各部分原始结果如下"
          f"（如果这里某一条写的是\"没有查到可信的答案\"，最终回答却仍然给出了"
          f"这一条对应的具体内容，就能确认是大模型自己补的，不是真的查到的）：\n"
          f"{parts_text}")

    user_content = f"用户最初问的问题：{original_text}\n\n拆解后各部分的结果：\n\n{parts_text}"
    messages = [
        {"role": "system", "content": _SYNTHESIZE_SYSTEM_PROMPT + LENGTH_RULE + current_time_line()},
        {"role": "user", "content": user_content},
    ]
    reply = client.chat(messages, caller="synthesize()")
    if reply is None or not reply.strip():
        return None
    return reply.strip()


_DETECT_CANDIDATES_SYSTEM_PROMPT = """\
你是一个记忆系统里负责"核对答案是否存在多个候选"的组件。你会收到一个问题、
一段已经确认跟这个问题相关的原始资料，以及已经生成好的一句自然语言回答。

有些问题的真实答案在原始资料里其实不止一个（比如"A的姐妹是谁"，资料里其实
提到了两个姐妹，但生成回答那一步只挑了其中一个说出来）。你的任务是仔细核对
原始资料本身（不是只看那句已经生成好的回答），如果资料里明确提到了不止一个
能满足这个问题的候选，把所有这些候选的名字都列出来；候选必须是资料里真实、
明确出现的具体名字，不能自己推测或联想资料里没写的内容。

如果资料里只有一个候选，或者这个问题本身问的不是"是谁/是哪个"这种可能存在
多个具体候选的内容（比如问的是数值、描述性内容，这种答案本身通常就是唯一的），
只需要把那句已生成回答里提到的那个候选原样放进数组，输出一个元素即可，不要
为了凑"多候选"而拆分本来就是单一整体的内容。

按格式输出JSON，不要输出JSON之外的任何文字：
{"candidates": ["候选1", "候选2", ...]}

几个例子：

输入：
问题：玛恩纳的侄女是谁？
原始资料：（资料中提到玛恩纳有两个侄女：瑕光和临光）
已生成的回答：玛恩纳的侄女是瑕光。
输出：{"candidates": ["瑕光", "临光"]}
（资料里其实提到了两个侄女，虽然生成的回答只挑了一个说，但两个都要列出来）

输入：
问题：能天使是什么职业？
原始资料：（资料中只提到能天使是狙击干员）
已生成的回答：能天使的职业是狙击。
输出：{"candidates": ["狙击"]}
（资料里只有一个明确答案，不存在多候选歧义）

输入：
问题：能天使精二的攻击力是多少？
原始资料：（资料中给出了具体数值）
已生成的回答：能天使精二满级攻击力是753。
输出：{"candidates": ["753"]}
（这类具体数值问题本来就不是"多个候选实体消歧"的场景，原样放回那个具体值
即可，不要强行拆分）

只输出JSON对象本身，不要加任何解释、不要用markdown代码块包裹。
"""


def detect_answer_candidates(query: str, source_text: str, generated_answer: str, client) -> List[str]:
    """F（多候选页面消歧）的第一步："都查一遍、合并回答"这个策略要求先
    知道"这一跳到底有没有不止一个候选"。只在`conversation_memory.py`的
    `_answer_multi_hop()`判断"这个子查询的结果会被后面的子查询依赖"
    （`referenced_ids`）时才会调用，普通单轮问答、独立并列子查询完全不
    受影响，完整设计动机见本文件模块开头"F正式实现"一节。

    source_text：这一跳检索到的原始资料全文（比如`fetch_page_for_answer()`
    返回的wiki整页正文），不是`generated_answer`那句已经生成好的自然语言
    回答——核对候选必须看原文，因为"从多个候选里挑一个说出来"这件事恰恰
    发生在生成这一步，生成完的文本里天然只剩一个名字，看不出原文里其实
    还有别的候选。

    返回候选名字符串列表，最多`MAX_CANDIDATES`个（超出的截断，见模块开头
    "候选数量上限"一节）。长度<=1时，调用方（`_answer_multi_hop()`）视为
    "没有歧义"，跟这个函数完全没被调用过一样往下走单一分支。

    client不可用/调用失败/返回的不是合法JSON，一律返回`[generated_answer]`
    ——退化成"只有生成回答里那一个候选"，等价于完全不检测，这是最保守的
    降级路径，不会因为这一步失败就影响原有的单分支流程。
    """
    if not getattr(client, "is_real", False):
        return [generated_answer]

    messages = [
        {"role": "system", "content": _DETECT_CANDIDATES_SYSTEM_PROMPT},
        {"role": "user", "content": f"问题：{query}\n原始资料：{source_text}\n已生成的回答：{generated_answer}"},
    ]
    raw = client.chat(messages, caller="detect_answer_candidates()")
    if raw is None:
        return [generated_answer]

    parsed = try_parse_json(strip_json_fence(raw))
    if not isinstance(parsed, dict):
        return [generated_answer]
    candidates = parsed.get("candidates")
    if not isinstance(candidates, list) or not candidates or not all(
        isinstance(c, str) and c.strip() for c in candidates
    ):
        return [generated_answer]

    seen = set()
    deduped = []
    for c in candidates:
        c = c.strip()
        if c not in seen:
            seen.add(c)
            deduped.append(c)
    if len(deduped) > MAX_CANDIDATES:
        print(f"[query_planner] 候选数量（{len(deduped)}）超过上限"
              f"MAX_CANDIDATES={MAX_CANDIDATES}，截断到前{MAX_CANDIDATES}个：{deduped}")
        deduped = deduped[:MAX_CANDIDATES]
    return deduped


