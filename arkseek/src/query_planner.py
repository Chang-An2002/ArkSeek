# ============================================================
#
# 起因：run_tests.py 里"lineage tracing课题使用的是什么动物的什么组织？"这条
# 已知局限，阶段一一直归因为"精排对一次问两件事的复合问法系统性打低分"。
# 2026-09-24重新做变量分离实验（同一个片段79，同一个精排模型）推翻了这个
# 结论：复合/单一问法分数几乎一样（0.039 vs 0.056；0.968 vs 0.962），真正
# 决定分数的是措辞——问题用英文"lineage tracing"，原文写的是中文"谱系标记""
# CRISPR条形码系统"，把问题里的英文术语换成"谱系追踪"就从0.04升到0.5左右。
# 阶段一那次对照实验同时改了"拆分"和"措辞"两个变量，把措辞的效果误记在了
# 拆分头上，完整经过见README"关于精排与已知局限"一节。
#
# 跟已有几处改写的分工（为什么不复用）：
# - decompose()：只管"分不分开查、先查什么、去哪查"，不改用词
# - resolve_for_retrieval()：只借上下文补全代词/省略，约定是"已经完整就原样
#   输出"（㉔就是它改写了不该改的句子），而且也作用于L2——用户历史发言本来
#   就是用户自己的措辞，把问题换成书面术语反而会跟历史原文对不上
# - wiki路由的关键词抽取：wiki整页交给LLM读，没有"逐片段精排+gate"这一步，
#   LLM自己懂lineage tracing=谱系追踪，天然不受这个问题影响
# 所以单独设计：只给L3用，只在gate第一次没过时调用（见
# pipeline.retrieve_with_gate()），改写出的问法同时参与召回和精排打分。
#
# 最重要的约束：改写不能把LLM猜的答案写进问题（"课题是不是用了小鼠"），
# 否则等于让LLM用自己的猜测帮自己通过防幻觉gate。few-shot例子也刻意没用
# 测试集原句，第6题能不能被救回来才能说明方法本身有没有泛化能力。

_REWRITE_FOR_KB_SYSTEM_PROMPT = """\
你是一个检索辅助模块。知识库是中英文混合的：{OWNER}的中文课题报告和中文JC讲稿，
以及英文文献原文和英文PPT。检索时是拿用户问题跟文档原文做关键词匹配和语义
相关性打分——问题的用词（包括语言）跟原文差得越远，越容易查不到。你的任务：
把用户问题改写成1~2个意思完全相同、但更贴近文档原文用词的问法，供检索时额外
使用。

改写方向（跨语言查询扩展）：
- 优先给出一中一英两个问法：一个用中文书面文档里常见的说法（英文术语换成中文，
  可以在括号里保留英文），一个用英文学术文献里常见的说法
- 口语化、中英混杂的说法换成书面表达
- 专有名词（方法名、工具名、人名，比如LoxCode、CoSpar、ArchR）原样保留，不要翻译
- 问题的主语/限定词（比如"这个课题""{OWNER}""作者""这篇文献"）保留，不要删

严格禁止：
- 加入原问题没有的信息，尤其不能把你猜测的答案写进问题。比如原问题"这个
  课题用的什么测序平台？"，不能改成"这个课题是不是用了10x Genomics平台？"
  ——那等于用你的猜测替代检索，是这个系统最需要避免的事
- 改变问题问的是什么（不能把"用了什么"改成"为什么用"）

跟文档检索无关的问题（闲聊、生活问题）返回空列表，不要硬改。

输出格式：{"rewrites": ["改写1", "改写2"]}

例子：
问题：这个project的batch effect是怎么处理的？
输出：{"rewrites": ["这个课题的批次效应（batch effect）是怎么处理的？", "How is batch effect corrected in this project?"]}

问题：LoxCode是怎么产生高多样性条形码的？
输出：{"rewrites": ["How does LoxCode generate highly diverse barcodes?"]}
（原句已经是规范中文，只补一个英文问法）

问题：What problem does CoSpar solve?
输出：{"rewrites": ["CoSpar解决了什么问题？"]}

问题：这个课题用的什么测序平台？
输出：{"rewrites": ["What sequencing platform is used in this project?"]}
（绝不能改成带猜测答案的问法）

问题：今天晚饭吃什么？
输出：{"rewrites": []}

只输出JSON对象本身，不要加任何解释、不要用markdown代码块包裹。
"""
_REWRITE_FOR_KB_SYSTEM_PROMPT = fill_owner(_REWRITE_FOR_KB_SYSTEM_PROMPT)

MAX_KB_REWRITES = 2


def rewrite_for_kb(query: str, client) -> List[str]:
    """返回0~MAX_KB_REWRITES个改写问法（不含原句）。client不可用/调用失败/
    非法JSON/LLM判断不需要改写，一律返回空列表，调用方据此跳过重试，跟没有
    这一步完全一样。"""
    if not getattr(client, "is_real", False):
        return []

    messages = [
        {"role": "system", "content": _REWRITE_FOR_KB_SYSTEM_PROMPT},
        {"role": "user", "content": f"问题：{query}"},
    ]
    raw = client.chat(messages, caller="rewrite_for_kb()")
    if raw is None:
        return []

    parsed = try_parse_json(strip_json_fence(raw))
    if not isinstance(parsed, dict):
        return []
    rewrites = parsed.get("rewrites")
    if not isinstance(rewrites, list) or not all(isinstance(r, str) for r in rewrites):
        return []

    deduped = []
    for r in rewrites:
        r = r.strip()
        if r and r != query.strip() and r not in deduped:
            deduped.append(r)
    return deduped[:MAX_KB_REWRITES]


# ---------- 翻聊天记录没过门槛时的改写（2026-10-01） ----------
# 跟rewrite_for_kb()同一个思路（第一次没过门槛才调用、改写后再检索一次、改写路径用
# 更高的门槛），区别在改写成什么：知识库是书面文档，改写成"更贴近原文用词的问法"；
# 聊天记录是口语原话，"我不喜欢什么"跟"我不喜欢游泳，只喜欢骑行"这种问句对陈述句
# 精排打分偏低（真机0.38），所以改写成"当初可能是怎么说的"陈述句（业界叫HyDE，
# 用假设的答案去检索）。不知道的部分用"……"代替，不让模型猜具体内容。
_REWRITE_FOR_HISTORY_SYSTEM_PROMPT = """\
你是一个检索辅助模块。用户在问自己（或者跟助手）以前在聊天里说过的事，系统要在
聊天记录里找到当时那句话。聊天记录是口语原话，拿"问句"去匹配"当时说的陈述句"
效果很差，所以你要把问题改写成1~2句"当时可能是怎么说的"陈述句，供检索使用。

规则：
- 用陈述句、口语，保持原来的人称（"我"还是"我"，"我们组"还是"我们组"）
- 不知道的具体内容用"……"代替，**绝不能填你猜的答案**（比如不能写"我不喜欢游泳"，
  要写"我不喜欢……"）——那等于用猜测替代检索
- 问的是助手以前说过的（"你上次推荐我吃什么"），改写成助手当时可能的说法
  （"可以试试……"），也可以给出用户当时的提问（"今天晚饭吃什么"）
- 跟聊天记录无关的问题返回空列表
- 背景只用于解析省略的主题和对象，不当成答案。比如之前讨论中药，问“之前推荐什么”，
  可改写“中药可以考虑……”，不能从后来的总结推断具体药名，也不能丢掉中药这一主题。

输出格式：{"rewrites": ["陈述句1", "陈述句2"]}

例子：
问题：我不喜欢什么
输出：{"rewrites": ["我不喜欢……", "我讨厌……"]}

问题：我们组之前决定用什么做向量数据库来着？
输出：{"rewrites": ["我们组决定用……做向量数据库"]}

问题：你上次推荐我晚饭吃什么来着？
输出：{"rewrites": ["今天晚饭吃什么", "晚饭可以试试……"]}

问题：我之前说我明天几点要去哪
输出：{"rewrites": ["我明天……点要去……"]}

只输出JSON对象本身，不要加任何解释、不要用markdown代码块包裹。
"""


def rewrite_for_history(query: str, client, recent_context=None) -> List[str]:
    """返回0~2句改写成陈述句的检索用文本（不含原句）。不可用/失败/判断不需要，
    一律返回空列表，调用方据此跳过重试。"""
    if not getattr(client, "is_real", False):
        return []
    raw = client.chat([
        {"role": "system", "content": _REWRITE_FOR_HISTORY_SYSTEM_PROMPT},
        {"role": "user", "content": with_current_message(recent_context, f"问题：{query}")},
    ], caller="rewrite_for_history()")
    parsed = try_parse_json(strip_json_fence(raw)) if raw else None
    rewrites = parsed.get("rewrites") if isinstance(parsed, dict) else None
    if not isinstance(rewrites, list):
        return []
    out = []
    for r in rewrites:
        r = r.strip() if isinstance(r, str) else ""
        if r and r != query.strip() and r not in out:
            out.append(r)
    return out[:2]


